/**
 * BITÁCORA sintetizada para el seed (entorno de demo).
 * A partir de los ítems del checklist ya completos por etapa, genera una línea
 * de tiempo con fecha/hora y la persona que respondió cada punto, más los
 * cambios de etapa. Estos datos alimentan la bitácora de la tarea y las
 * métricas de tiempo de respuesta por persona del dashboard.
 */
function buildAuditTrail(task, users) {
  const byRole = {};
  users.forEach((u) => {
    if (!byRole[u.role]) byRole[u.role] = u.name;
  });
  const log = [];
  const created = task.createdAt ? +new Date(task.createdAt) : Date.now();
  let cursor = created + 2 * 3600000; // primera respuesta 2 h después de creada
  const STAGE_FLOW = ['backlog', 'in_progress', 'qa', 'uat', 'release'];

  STAGE_FLOW.forEach((stage, si) => {
    const items = (task.checklist || []).filter((i) => i.stage === stage);
    const doneItems = items.filter((i) => i.done);
    if (doneItems.length) {
      doneItems.forEach((item, idx) => {
        cursor += (7 + (idx * 5) % 9) * 3600000; // +7 a +15 h por punto
        log.push({
          id: `L${log.length + 1}`,
          at: new Date(cursor).toISOString(),
          type: 'checklist',
          key: item.key,
          stage,
          action: 'done',
          actor: byRole[item.role] || 'Sistema',
          role: item.role,
          note: '',
        });
      });
      // La etapa se dio por cerrada (avance) cuando esté completada y no sea la etapa actual de la tarea.
      const currentIdx = STAGE_FLOW.indexOf(task.status);
      if (si < currentIdx) {
        cursor += 4 * 3600000;
        log.push({
          id: `L${log.length + 1}`,
          at: new Date(cursor).toISOString(),
          type: 'stage',
          stage,
          action: 'advance',
          from: stage,
          to: STAGE_FLOW[si + 1],
          actor: 'Flujo automático',
          role: '',
          note: `Etapa "${STAGE_FLOW[si + 1]}" iniciada`,
        });
      }
    }
    cursor += 16 * 3600000; // turno de trabajo siguiente
  });

  return log;
}

